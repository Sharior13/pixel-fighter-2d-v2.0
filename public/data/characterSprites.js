// ============================================================================
// characterSprites.js — DERIVED VIEW, not a data source.
// ============================================================================
// Character sprite/animation config used to be authored directly in this
// file, duplicating data that also lived in server/data/characterData.js
// and server/core/attackSystem.js. It now all lives in ONE place -
// server/data/characters.js - as the single source of truth (see that
// file's header comment). This module just reshapes that data into the
// flat { [characterId]: { frameWidth, frameHeight, layout, scale,
// spriteSheets, animations } } shape the renderer (render.js) and
// assetPreloader.js already expect, so neither of those files needed to
// change.
//
// Imports from public/core/sim/data/characters.js, the browser-safe mirror
// of server/data/characters.js that scripts/build-client-sim.js generates -
// same mechanism this project already uses to share the combat sim itself
// between server and client (see public/core/sim/core/*.js). Do not author
// sprite data here; edit server/data/characters.js and run `npm run
// build:sim`.
//
// Also merges in ANIM_SEQUENCES (public/core/sim/data/generatedAnimSequences.js,
// itself generated by scripts/build-anim-sequences.js from characters.js's
// authored artFrames + attackSystem.js's per-character ATTACK_CONFIG timing -
// see that script's header comment) onto every 'tick-sequence' animation
// entry, so SpriteAnimator gets a real frameSequence array instead of having
// to know anything about how it's produced.
// ============================================================================
import { CHARACTERS } from "../core/sim/data/characters.js";
import { ANIM_SEQUENCES } from "../core/sim/data/generatedAnimSequences.js";

// Deliberately a hard error, not a silent skip/fallback: an animation
// authored with syncMode: 'tick-sequence' but no matching generated
// frameSequence means either the build step wasn't run after adding
// artFrames, or artFrames is missing entirely (build-anim-sequences.js
// itself already throws for that case - see its buildAnimSequences()) - in
// either case shipping that animation with no per-tick data would silently
// break playback (SpriteAnimator._updateTickSequence has nothing to index
// into) rather than surface the real problem at build/load time.
function resolveAnimations(characterId, animations) {
    return Object.fromEntries(
        Object.entries(animations).map(([moveId, animConfig]) => {
            if (animConfig.syncMode !== "tick-sequence") {
                return [moveId, animConfig];
            }

            const frameSequence = ANIM_SEQUENCES[characterId] && ANIM_SEQUENCES[characterId][moveId];
            if (!frameSequence) {
                throw new Error(
                    `[characterSprites] ${characterId}.${moveId}: syncMode is 'tick-sequence' but no generated ` +
                    `frameSequence was found in ANIM_SEQUENCES - run \`npm run build:sim\` after adding an ` +
                    `artFrames spec to this animation in server/data/characters.js.`
                );
            }

            return [moveId, { ...animConfig, frameSequence }];
        })
    );
}

const characterSpriteConfigs = Object.fromEntries(
    Object.entries(CHARACTERS).map(([characterId, character]) => [
        characterId,
        {
            name: character.name,
            ...character.sprite,
            animations: resolveAnimations(characterId, character.sprite.animations)
        }
    ])
);

export { characterSpriteConfigs };